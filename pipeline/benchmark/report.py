"""Report generation for benchmark results."""

import json
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path


def generate_report(results, G, entities_df, metadata_df, output_path, relations_df=None):
    """Generate benchmark_results.md from query results."""
    lines = []
    lines.append("# Benchmark Query Results")
    lines.append("")
    lines.append(f"**Generated:** {date.today().isoformat()}")
    lines.append(
        f"**Graph:** {G.number_of_nodes():,} nodes, "
        f"{G.number_of_edges():,} edges")
    inc_count = len(
        entities_df[entities_df.entity_type == "INCIDENT"])
    lines.append(
        f"**Records:** {len(metadata_df):,} metadata rows, "
        f"{inc_count:,} incident nodes")
    l2_count = 0
    if relations_df is not None and "relation" in relations_df.columns:
        l2_count = len(
            relations_df[relations_df["relation"].isin(
                ["CAUSAL", "PRECEDED_BY", "FAILED_CONTROL", "MITIGATED_BY"]
            )]
        )
    layer_label = (
        f"L1 + L2 ({l2_count:,} causal edges)" if l2_count > 0
        else "L1 only (pre-Layer 2 causal enrichment)"
    )
    lines.append(f"**Layer:** {layer_label}")
    lines.append("")

    # ── Summary Table ────────────────────────────────────────────────
    lines.append("## 1. Summary Table")
    lines.append("")
    lines.append("| ID | Query | Type | Status | Result |")
    lines.append("|------|-------|------|:------:|--------|")

    for qid in sorted(results.keys()):
        r = results[qid]
        cov = r.get('coverage', '❌')
        lines.append(
            f"| {qid} | {r['name']} | {r['type']} | "
            f"{cov} | {r.get('result_summary', '?')} |")
    lines.append("")

    # ── Coverage summary ─────────────────────────────────────────────
    passing = sum(1 for r in results.values()
                  if r.get("coverage") == "\u2705")
    non_passing = sum(1 for r in results.values()
                      if r.get("coverage") in ("\u26a0\ufe0f", "\u274c"))
    lines.append(
        f"**Overall:** {passing} \u2705 passing / "
        f"{non_passing} \u26a0\ufe0f non-passing out of {len(results)} queries")
    lines.append("")

    # ── Per-Query Detail ─────────────────────────────────────────────
    lines.append("## 2. Per-Query Details")
    lines.append("")

    for qid in sorted(results.keys()):
        r = results[qid]
        lines.append(f"### {qid}: {r['name']}")
        lines.append(
            f"**Type:** {r['type']} | **Status:** {r.get('coverage', '❌')} | "
            f"**Time:** {r.get('elapsed', '?')}")
        lines.append("")
        lines.append("```")
        lines.append(r.get("detail", ""))
        lines.append("```")
        lines.append("")

    # ── Failures ─────────────────────────────────────────────────────
    failing_queries = [
        (qid, r) for qid, r in sorted(results.items())
        if r.get("coverage") != "\u2705"
    ]
    if failing_queries:
        lines.append("## 3. Failing Queries")
        lines.append("")
        for qid, r in failing_queries:
            lines.append(f"- **{qid}** ({r['name']}): {r.get('result_summary', '?')}")
        lines.append("")

    # ── Regression Snapshot ────────────────────────────────────────────
    snapshot_path = Path(output_path).parent / "benchmark_snapshot.json"
    current_snapshot = {}
    for qid, r in results.items():
        current_snapshot[qid] = {
            "name": r["name"],
            "coverage": r.get("coverage", "❌"),
            "result_summary": r.get("result_summary", "?"),
        }

    previous_snapshot = None
    if snapshot_path.exists():
        try:
            previous_snapshot = json.loads(snapshot_path.read_text())
        except (json.JSONDecodeError, OSError):
            previous_snapshot = None

    if previous_snapshot:
        lines.append("## 4. Regression Diff (vs previous run)")
        lines.append("")
        changes = []
        for qid in sorted(
                set(current_snapshot) | set(previous_snapshot)):
            prev = previous_snapshot.get(qid)
            curr = current_snapshot.get(qid)
            if curr and not prev:
                changes.append(f"- **{qid}**: NEW")
            elif prev and not curr:
                changes.append(f"- **{qid}**: REMOVED")
            elif prev and curr:
                if prev.get("coverage") != curr.get("coverage"):
                    changes.append(
                        f"- **{qid}**: {prev.get('coverage', '?')} → {curr.get('coverage', '?')}")
        if changes:
            lines.extend(changes)
        else:
            lines.append("No regressions — all results stable.")
        lines.append("")

    # Save current snapshot
    snapshot_path.write_text(
        json.dumps(current_snapshot, indent=2, ensure_ascii=False))
    print(f"Snapshot written to {snapshot_path}")

    lines.append("---")
    lines.append(
        "*Generated by pipeline/benchmark/run_benchmark.py*")

    output_path = Path(output_path)
    output_path.write_text("\n".join(lines))
    print(f"\nReport written to {output_path}")
